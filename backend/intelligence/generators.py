# 2. Standard PDF 1.4 Document Generator (.pdf)
# ==============================================================================

class PdfGenerator:
    """Generates 100% valid PDF 1.4 documents natively with formatted typography and page catalog."""

    @classmethod
    def generate_pdf(
        cls,
        title: str,
        content_lines: List[str],
        author: str = "Copetra AI"
    ) -> bytes:
        """Generates a structured, standard PDF 1.4 binary stream."""
        # Sanitize text
        clean_title = re.sub(r'[^\x20-\x7E]', ' ', title)[:80]
        sanitized_lines = []
        for line in content_lines:
            clean = re.sub(r'[^\x20-\x7E]', ' ', line)
            # word wrap roughly 80 chars
            while len(clean) > 85:
                sanitized_lines.append(clean[:85])
                clean = "  " + clean[85:]
            sanitized_lines.append(clean)

        # Build text stream
        text_ops = [
            "BT",
            "/F1 18 Tf",
            "50 750 Td",
            f"({clean_title}) Tj",
            "/F1 10 Tf",
            "0 -20 Td",
            f"(Generated by {author} on {datetime.now(timezone.utc).strftime('%Y-%m-%d')}) Tj",
            "0 -30 Td",
            "/F1 11 Tf",
        ]

        y = 700
        for sl in sanitized_lines[:45]:  # fit first page
            # Escape parenthesis in PDF strings
            escaped = sl.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
            text_ops.append("0 -15 Td")
            text_ops.append(f"({escaped}) Tj")
        text_ops.append("ET")

        stream_data = "\n".join(text_ops).encode("latin-1", "replace")
        stream_len = len(stream_data)

        objects = []
        # Object 1: Catalog
        objects.append(b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")
        # Object 2: Pages
        objects.append(b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n")
        # Object 3: Page
        objects.append(
            b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
            b"/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n"
        )
        # Object 4: Stream
        objects.append(
            f"4 0 obj\n<< /Length {stream_len} >>\nstream\n".encode("latin-1")
            + stream_data
            + b"\nendstream\nendobj\n"
        )
        # Object 5: Font
        objects.append(
            b"5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n"
        )

        # Assemble PDF with byte offsets
        pdf_buf = io.BytesIO()
        pdf_buf.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")

        offsets = [0]
        for obj in objects:
            offsets.append(pdf_buf.tell())
            pdf_buf.write(obj)

        xref_offset = pdf_buf.tell()
        pdf_buf.write(f"xref\n0 {len(offsets)}\n".encode("latin-1"))
        pdf_buf.write(b"0000000000 65535 f \n")
        for off in offsets[1:]:
            pdf_buf.write(f"{off:010d} 00000 n \n".encode("latin-1"))

        pdf_buf.write(
            f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n".encode("latin-1")
        )

        return pdf_buf.getvalue()


