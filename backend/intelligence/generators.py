# 7. Safe File Converter
# ==============================================================================

class FileConverter:
    """Safely converts between structured formats."""

    @staticmethod
    def csv_to_xlsx(csv_bytes: bytes, sheet_name: str = "Data") -> bytes:
        text = csv_bytes.decode("utf-8", errors="replace")
        reader = csv.reader(io.StringIO(text))
        rows = list(reader)
        if not rows:
            return XlsxGenerator.generate_xlsx(sheet_name, ["Empty"], [["No Data"]])
        headers = rows[0]
        data_rows = rows[1:] if len(rows) > 1 else []
        return XlsxGenerator.generate_xlsx(sheet_name, headers, data_rows)

    @staticmethod
    def json_to_csv(json_bytes: bytes) -> bytes:
        data = json.loads(json_bytes.decode("utf-8"))
        if isinstance(data, list) and data and isinstance(data[0], dict):
            headers = list(data[0].keys())
            rows = [[item.get(h, "") for h in headers] for item in data]
            return StructuredDataGenerator.generate_csv(headers, rows)
        return StructuredDataGenerator.generate_csv(["Key", "Value"], list(data.items()) if isinstance(data, dict) else [["Data", str(data)]])
