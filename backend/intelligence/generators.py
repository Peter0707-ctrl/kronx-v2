# 5. CSV, TSV, JSON & Markdown Structured Generators
# ==============================================================================

class StructuredDataGenerator:
    """Generates structured CSV, TSV, JSON, Markdown, and TXT files."""

    @staticmethod
    def generate_csv(headers: List[str], rows: List[List[Any]], delimiter: str = ",") -> bytes:
        out = io.StringIO()
        writer = csv.writer(out, delimiter=delimiter)
        if headers:
            writer.writerow(headers)
        writer.writerows(rows)
        return out.getvalue().encode("utf-8")

    @staticmethod
    def generate_json(data: Any, indent: int = 2) -> bytes:
        return json.dumps(data, indent=indent, ensure_ascii=False).encode("utf-8")

    @staticmethod
    def generate_markdown(title: str, sections: List[Dict[str, str]]) -> bytes:
        lines = [f"# {title}\n"]
        for sec in sections:
            h = sec.get("heading")
            c = sec.get("content", "")
            if h:
                lines.append(f"## {h}\n")
            lines.append(f"{c}\n")
        return "\n".join(lines).encode("utf-8")


