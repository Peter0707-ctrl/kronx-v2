# 1. OpenXML Word Document Generator (.docx)
# ==============================================================================

class DocxGenerator:
    """Generates 100% valid Microsoft Word .docx files natively without external dependencies."""

    @staticmethod
    def _escape_xml(text: str) -> str:
        return (
            str(text)
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
            .replace("'", "&apos;")
        )

    @classmethod
    def generate_docx(
        cls,
        title: str,
        sections: List[Dict[str, Any]],
        author: str = "Copetra AI",
        subtitle: Optional[str] = None
    ) -> bytes:
        """
        sections format:
        [
            {"type": "heading", "level": 1|2|3, "text": "..."},
            {"type": "paragraph", "text": "..."},
            {"type": "bullet", "text": "..."},
            {"type": "table", "headers": ["A", "B"], "rows": [["1", "2"]]}
        ]
        """
        body_xml = []

        # Title
        body_xml.append(
            f'<w:p><w:pPr><w:pStyle w:val="Title"/><w:jc w:val="center"/></w:pPr>'
            f'<w:r><w:rPr><w:b/><w:sz w:val="48"/><w:color w:val="1E293B"/></w:rPr>'
            f'<w:t>{cls._escape_xml(title)}</w:t></w:r></w:p>'
        )

        if subtitle:
            body_xml.append(
                f'<w:p><w:pPr><w:jc w:val="center"/></w:pPr>'
                f'<w:r><w:rPr><w:i/><w:sz w:val="24"/><w:color w:val="64748B"/></w:rPr>'
                f'<w:t>{cls._escape_xml(subtitle)}</w:t></w:r></w:p>'
            )

        # Meta spacing
        body_xml.append(
            f'<w:p><w:pPr><w:jc w:val="center"/></w:pPr>'
            f'<w:r><w:rPr><w:sz w:val="18"/><w:color w:val="94A3B8"/></w:rPr>'
            f'<w:t>Generated by {cls._escape_xml(author)} • {datetime.now(timezone.utc).strftime("%B %d, %Y")}</w:t></w:r></w:p>'
        )
        body_xml.append('<w:p><w:r><w:t></w:t></w:r></w:p>')

        for sec in sections:
            stype = sec.get("type", "paragraph")
            text = sec.get("text", "")

            if stype == "heading":
                lvl = sec.get("level", 1)
                sz = "36" if lvl == 1 else ("28" if lvl == 2 else "24")
                color = "0F172A" if lvl == 1 else ("2563EB" if lvl == 2 else "334155")
                body_xml.append(
                    f'<w:p><w:pPr><w:pStyle w:val="Heading{lvl}"/><w:spacing w:before="240" w:after="120"/></w:pPr>'
                    f'<w:r><w:rPr><w:b/><w:sz w:val="{sz}"/><w:color w:val="{color}"/></w:rPr>'
                    f'<w:t>{cls._escape_xml(text)}</w:t></w:r></w:p>'
                )

            elif stype == "bullet":
                body_xml.append(
                    f'<w:p><w:pPr><w:pStyle w:val="ListBullet"/><w:ind w:left="360"/><w:spacing w:after="80"/></w:pPr>'
                    f'<w:r><w:rPr><w:sz w:val="22"/><w:color w:val="334155"/></w:rPr>'
                    f'<w:t>• {cls._escape_xml(text)}</w:t></w:r></w:p>'
                )

            elif stype == "table":
                headers = sec.get("headers", [])
                rows = sec.get("rows", [])
                tbl_xml = [
                    '<w:tbl>',
                    '<w:tblPr><w:tblW w:w="5000" w:type="pct"/><w:tblBorders>'
                    '<w:top w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                    '<w:left w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                    '<w:bottom w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                    '<w:right w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                    '<w:insideH w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>'
                    '<w:insideV w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>'
                    '</w:tblBorders></w:tblPr>'
                ]
                if headers:
                    tbl_xml.append('<w:tr><w:trPr><w:tblHeader/></w:trPr>')
                    for h in headers:
                        tbl_xml.append(
                            f'<w:tc><w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="F1F5F9"/></w:tcPr>'
                            f'<w:p><w:r><w:rPr><w:b/><w:sz w:val="20"/><w:color w:val="0F172A"/></w:rPr>'
                            f'<w:t>{cls._escape_xml(h)}</w:t></w:r></w:p></w:tc>'
                        )
                    tbl_xml.append('</w:tr>')
                for r in rows:
                    tbl_xml.append('<w:tr>')
                    for c in r:
                        tbl_xml.append(
                            f'<w:tc><w:p><w:r><w:rPr><w:sz w:val="20"/><w:color w:val="334155"/></w:rPr>'
                            f'<w:t>{cls._escape_xml(c)}</w:t></w:r></w:p></w:tc>'
                        )
                    tbl_xml.append('</w:tr>')
                tbl_xml.append('</w:tbl>')
                body_xml.append(''.join(tbl_xml))

            else:  # standard paragraph
                body_xml.append(
                    f'<w:p><w:pPr><w:spacing w:after="160"/></w:pPr>'
                    f'<w:r><w:rPr><w:sz w:val="22"/><w:color w:val="334155"/></w:rPr>'
                    f'<w:t>{cls._escape_xml(text)}</w:t></w:r></w:p>'
                )

        doc_xml_str = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">\n'
            f'<w:body>{"".join(body_xml)}'
            '<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr>'
            '</w:body></w:document>'
        )

        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
            '<Default Extension="xml" ContentType="application/xml"/>\n'
            '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>\n'
            '</Types>'
        )

        rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>\n'
            '</Relationships>'
        )

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("[Content_Types].xml", content_types)
            z.writestr("_rels/.rels", rels)
            z.writestr("word/document.xml", doc_xml_str)

        return buf.getvalue()


