# 6. Diagram & Visual Map Generator (Mermaid & SVG)
# ==============================================================================

class DiagramGenerator:
    """Generates Mermaid diagrams, SVG flowcharts, and architecture charts."""

    @staticmethod
    def generate_mermaid_flowchart(nodes: List[Tuple[str, str]], links: List[Tuple[str, str, Optional[str]]]) -> str:
        lines = ["graph TD"]
        for nid, nlabel in nodes:
            clean_label = nlabel.replace('"', "'")
            lines.append(f'    {nid}["{clean_label}"]')
        for src, dst, lbl in links:
            if lbl:
                lines.append(f'    {src} -->|"{lbl}"| {dst}')
            else:
                lines.append(f'    {src} --> {dst}')
        return "\n".join(lines)

    @staticmethod
    def generate_svg_chart(title: str, items: List[Tuple[str, float]], chart_type: str = "bar") -> bytes:
        """Generates standard SVG vector graphic."""
        width = 600
        height = 350
        max_val = max([val for _, val in items]) if items else 100.0
        if max_val <= 0:
            max_val = 1.0

        svg_parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
            '<rect width="100%" height="100%" fill="#0f172a" rx="12"/>',
            f'<text x="30" y="40" fill="#f8fafc" font-family="sans-serif" font-size="18" font-weight="bold">{DocxGenerator._escape_xml(title)}</text>',
        ]

        bar_x = 50
        bar_width = min(60, int((width - 100) / max(1, len(items))))
        for label, val in items:
            bar_height = int((val / max_val) * 200)
            bar_y = 280 - bar_height
            svg_parts.append(
                f'<rect x="{bar_x}" y="{bar_y}" width="{bar_width - 10}" height="{bar_height}" fill="#38bdf8" rx="4"/>'
            )
            svg_parts.append(
                f'<text x="{bar_x + 5}" y="{bar_y - 8}" fill="#38bdf8" font-family="sans-serif" font-size="12">{val}</text>'
            )
            svg_parts.append(
                f'<text x="{bar_x}" y="305" fill="#94a3b8" font-family="sans-serif" font-size="11">{DocxGenerator._escape_xml(label[:8])}</text>'
            )
            bar_x += bar_width

        svg_parts.append('</svg>')
        return "\n".join(svg_parts).encode("utf-8")


