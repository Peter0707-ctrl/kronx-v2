# 3. OpenXML Excel Spreadsheet Generator (.xlsx)
# ==============================================================================

class XlsxGenerator:
    """Generates 100% valid Microsoft Excel .xlsx spreadsheets natively."""

    @classmethod
    def generate_xlsx(
        cls,
        sheet_name: str,
        headers: List[str],
        rows: List[List[Any]]
    ) -> bytes:
        """Builds a multi-row .xlsx file."""
        sheet_rows = []

        def cell_xml(col_idx: int, row_idx: int, val: Any) -> str:
            col_letter = chr(65 + (col_idx % 26))
            cell_ref = f"{col_letter}{row_idx}"
            if isinstance(val, (int, float)):
                return f'<c r="{cell_ref}"><v>{val}</v></c>'
            esc = DocxGenerator._escape_xml(str(val))
            return f'<c r="{cell_ref}" t="inlineStr"><is><t>{esc}</t></is></c>'

        # Header row
        if headers:
            h_cells = [cell_xml(i, 1, h) for i, h in enumerate(headers)]
            sheet_rows.append(f'<row r="1" customHeight="1" ht="24">{"".join(h_cells)}</row>')

        # Data rows
        start_row = 2 if headers else 1
        for r_idx, row in enumerate(rows, start=start_row):
            cells = [cell_xml(c_idx, r_idx, val) for c_idx, val in enumerate(row)]
            sheet_rows.append(f'<row r="{r_idx}">{"".join(cells)}</row>')

        sheet_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">\n'
            f'<sheetData>{"".join(sheet_rows)}</sheetData>\n'
            '</worksheet>'
        )

        workbook_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">\n'
            f'<sheets><sheet name="{DocxGenerator._escape_xml(sheet_name[:31])}" sheetId="1" r:id="rId1"/></sheets>\n'
            '</workbook>'
        )

        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
            '<Default Extension="xml" ContentType="application/xml"/>\n'
            '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>\n'
            '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>\n'
            '</Types>'
        )

        rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>\n'
            '</Relationships>'
        )

        wb_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>\n'
            '</Relationships>'
        )

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("[Content_Types].xml", content_types)
            z.writestr("_rels/.rels", rels)
            z.writestr("xl/workbook.xml", workbook_xml)
            z.writestr("xl/_rels/workbook.xml.rels", wb_rels)
            z.writestr("xl/worksheets/sheet1.xml", sheet_xml)

        return buf.getvalue()


