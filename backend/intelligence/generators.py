class PptxGenerator:
    """Generates 100% valid Microsoft PowerPoint .pptx presentations natively."""

    @classmethod
    def generate_pptx(
        cls,
        presentation_title: str,
        slides: List[Dict[str, Any]]
    ) -> bytes:
        """
        slides format:
        [
            {"title": "Slide Title", "bullets": ["Point 1", "Point 2"]},
            ...
        ]
        """
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            # Slides creation
            slide_ids_xml = []
            slide_rels_xml = []
            content_types_overrides = []

            for idx, slide_data in enumerate(slides, start=1):
                stitle = DocxGenerator._escape_xml(slide_data.get("title", f"Slide {idx}"))
                bullets = slide_data.get("bullets", [])

                bullet_p_xml = []
                for b in bullets:
                    bullet_p_xml.append(
                        f'<a:p><a:pPr lvl="0"/><a:r><a:rPr lang="en-US" sz="2000"/>'
                        f'<a:t>• {DocxGenerator._escape_xml(str(b))}</a:t></a:r></a:p>'
                    )

                slide_xml = (
                    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                    '<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
                    'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
                    'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">\n'
                    '<p:cSld><p:spTree>'
                    '<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
                    '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>'
                    # Title Box
                    f'<p:sp><p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr><p:ph type="title"/></p:nvPr></p:nvSpPr>'
                    f'<p:spPr><a:xfrm><a:off x="838200" y="609600"/><a:ext cx="7467600" cy="1143000"/></a:xfrm></p:spPr>'
                    f'<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US" sz="3600" b="1"/><a:t>{stitle}</a:t></a:r></a:p></p:txBody></p:sp>'
                    # Content Box
                    f'<p:sp><p:nvSpPr><p:cNvPr id="3" name="Content"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr><p:ph idx="1"/></p:nvPr></p:nvSpPr>'
                    f'<p:spPr><a:xfrm><a:off x="838200" y="1905000"/><a:ext cx="7467600" cy="4572000"/></a:xfrm></p:spPr>'
                    f'<p:txBody><a:bodyPr/><a:lstStyle/>{"".join(bullet_p_xml)}</p:txBody></p:sp>'
                    '</p:spTree></p:cSld></p:sld>'
                )

                z.writestr(f"ppt/slides/slide{idx}.xml", slide_xml)
                slide_ids_xml.append(f'<p:sldId id="{255 + idx}" r:id="rId{idx}"/>')
                slide_rels_xml.append(
                    f'<Relationship Id="rId{idx}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide{idx}.xml"/>'
                )
                content_types_overrides.append(
                    f'<Override PartName="/ppt/slides/slide{idx}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>'
                )

            # Presentation root
            pres_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
                'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
                'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">\n'
                f'<p:sldIdLst>{"".join(slide_ids_xml)}</p:sldIdLst>\n'
                '<p:sldSz cx="9144000" cy="6858000" type="screen4x3"/>\n'
                '</p:presentation>'
            )

            pres_rels = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
                f'{"".join(slide_rels_xml)}\n'
                '</Relationships>'
            )

            content_types = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
                '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
                '<Default Extension="xml" ContentType="application/xml"/>\n'
                '<Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>\n'
                f'{"".join(content_types_overrides)}\n'
                '</Types>'
            )

            pkg_rels = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
                '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>\n'
                '</Relationships>'
            )

            z.writestr("[Content_Types].xml", content_types)
            z.writestr("_rels/.rels", pkg_rels)
            z.writestr("ppt/presentation.xml", pres_xml)
            z.writestr("ppt/_rels/presentation.xml.rels", pres_rels)

        return buf.getvalue()


